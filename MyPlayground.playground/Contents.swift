"""
여러분의 과제는 다음과 같습니다. 선택적으로 정수 배열을 입력받아 무작위로 하나의 숫자를 반환하는 함수를 작성하세요. 배열이 없거나 입력받지 못한 경우에는 1부터 100 사이의 무작위 숫자를 반환해야 합니다.

이게 쉬워 보인다면, 아직 함정을 설명하지 않았기 때문입니다. 저는 여러분이 함수를 단 한 줄의 코드로 작성하길 바랍니다. 물론, 단순히 코드를 잔뜩 작성한 다음 줄 바꿈을 모두 지우라는 뜻은 아닙니다. 이 모든 내용을 단 한 줄의 코드로 작성할 수 있어야 합니다.
"""

func randNum(numbers: [Int]?) -> Int {
    numbers?.randomElement() ?? Int.random(in: 1...100)
}
